    def _call_groq(self, history: List[Dict[str, str]], current_input: str, chat_id: int = 0) -> Optional[str]:
        """Виклик Groq API з підтримкою ротації ключів та швидким фолбеком на Gemini"""
        if not self._groq_clients:
            return self._call_gemini_fallback(history, current_input)

        messages = [{"role": "system", "content": CYBER_RIZHYI_SYSTEM_PROMPT}]
        # Передаємо останні 8 реплік для збереження ліміту токенів TPM
        messages.extend(history[-8:])
        msg_line = current_input.split("\n")[0][:120]
        directive = (
            f"\n[ПРІОРИТЕТ №1 — ВІДПОВІДАЙ КОНКРЕТНО НА: «{msg_line}». НЕ ІГНОРУЙ ЩО НАПИСАНО. "
            "Якщо запитали про аватарку — відповідай про аватарку. Якщо щось показали — коментуй конкретно. "
            "Якщо образили чи підкололи — реагуй на суть, а не загальними фразами. "
            "ПРАВИЛО ТЕГІВ: СТРОГО ЗАБОРОНЕНО ТЕГАТИ КЕНТІВ ЧЕРЕЗ @! НІЯКИХ ТЕГІВ! "
            "Відповідай без @ тегів, тільки жива пацанська розмова. "
            "СТРОГО ЗАБОРОНЕНО чисті літературні слова: замість 'знахабнів' тільки 'ахуєл пес' або 'обнаглєл'. "
            "СТРОГО ЗАБОРОНЕНО односкладові відмовки: 'ок', 'пр', 'да', 'пон', 'і шо', 'хз', 'а ок', 'спс'! "
            "ФОРМАТ: Пиши ПЕРЕВАЖНО ОДНЕ коротке живе повідомлення (до 6-8 слів). "
            "Тільки якщо це окремий дойоб або рима, розбий на 2 короткі репліки через '|||'. "
            "Уникай розбиття на 3 репліки! Без '!'.]"
        )
        messages.append({"role": "user", "content": f"{current_input}{directive}"})

        max_attempts = len(self._groq_clients)
        for attempt in range(max_attempts):
            client = self._groq_client
            if not client:
                break
            try:
                logger.info(f"Виклик Groq API ({self.model}) на ключі #{self._key_index + 1}...")
                completion = client.chat.completions.create(
                    model=self.model,
                    messages=messages,
                    temperature=0.92,
                    max_tokens=90,
                    top_p=0.95
                )
                text = completion.choices[0].message.content
                if text and not is_ai_refusal(text):
                    return clean_bot_reply(text.strip())
            except Exception as e:
                err_str = str(e)
                logger.warning(f"Groq ключ #{self._key_index + 1} помилка: {err_str}")
                # МИТТЄВИЙ fallback на qwen/qwen3.8-27b при будь-якому 429 чи rate limit
                if "429" in err_str or "rate_limit" in err_str.lower() or "limit" in err_str.lower():
                    try:
                        logger.info("Groq 120B в ліміті, перемикаємось на Qwen 27B...")
                        compact_qwen = [
                            {"role": "system", "content": "Ти Саня Рижий з Чернівців (@sigma rigiu). Спілкуйся живою пацанською мовою, активно розвивай діалог, запитуй, підколюй. Пиши 2-3 короткі репліки через '|||' без '!' і СТРОГО без 'ок'/'пр'/'хз'. Замість 'знахабнів' пиши 'ахуєл пес'."},
                            *messages[1:][-4:]
                        ]
                        qwen_comp = client.chat.completions.create(
                            model="qwen/qwen3.8-27b",
                            messages=compact_qwen,
                            temperature=0.92,
                            max_tokens=90
                        )
                        q_text = qwen_comp.choices[0].message.content
                        if q_text and not is_ai_refusal(q_text):
                            return clean_bot_reply(q_text.strip())
                    except Exception as qe:
                        logger.debug(f"Qwen error: {qe}")
                self._rotate_groq_key()
                if "429" in err_str or "rate_limit" in err_str.lower():
                    continue
                else:
                    break
        # Якщо всі Groq ключі вичерпано/429 — прямий фолбек на Gemini 3.8 Flash
        logger.info("Усі Groq ключі недоступні, викликаємо Gemini 3.8 Flash...")
        return self._call_gemini_fallback(history, current_input)

    def _call_gemini_fallback(self, history: List[Dict[str, str]], current_input: str) -> Optional[str]:
        """Резервний виклик через Gemini AI якщо Groq офлайн"""
        prompt = f"{CYBER_RIZHYI_SYSTEM_PROMPT}\n\nПопередня розмова в чаті (контекст):\n"
        for h in history[-8:]:
            prompt += f"{h['content']}\n"
        msg_gem = current_input.split("\n")[0][:120]
        prompt += f"\nПоточне повідомлення:\n{current_input}\n\n[ОБОВ\'ЯЗКОВО ВІДПОВІДАЙ САМЕ НА: «{msg_gem}». НЕ копіюй заготовлені фрази — відповідай конкретно! Відповідай БЕЗ @ тегів. Якщо образили — римуй на ім'я. Замість 'знахабнів' пиши 'ахуєл пес' або 'обнаглєл'. Розбий відповідь на 2-3 короткі репліки через '|||'. Без \'!\'.]"

        try:
            if getattr(gemini_service, "is_new_sdk", False) and gemini_service.client:
                resp = gemini_service.client.models.generate_content(
                    model=gemini_service.model_name,
                    contents=[prompt]
                )
                return clean_bot_reply(resp.text.strip())
            elif hasattr(gemini_service, "legacy_model"):
                resp = gemini_service.legacy_model.generate_content([prompt])
                return clean_bot_reply(resp.text.strip())
        except Exception as e:
            logger.warning(f"Gemini fallback помилка: {e}")
        return None

